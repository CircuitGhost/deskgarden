void drawChar5x7(uint16_t* buffer, int16_t bufWidth, int16_t bufHeight, 
                 int16_t x, int16_t y, char c, uint16_t color) {
    if (!buffer || y >= bufHeight || (y + 7) < 0) return;

    // Convert lowercase to uppercase for uniform micro typography
    if (c >= 'a' && c <= 'z') {
        c -= 32;
    }

    uint8_t index = 0;
    if (c >= 32 && c <= 90) {
        index = c - 32;
    } else if (c == (char)0xB0 || c == '^') { // Degree sign
        index = 59;
    } else if (c == '|') {
        index = 60;
    } else {
        index = 0; // Space / unknown
    }

    const uint8_t* charCols = micro_font_5x7[index];

    for (int col = 0; col < 5; col++) {
        int16_t px = x + col;
        if (px < 0 || px >= bufWidth) continue;

        uint8_t colBits = charCols[col];
        for (int row = 0; row < 7; row++) {
            int16_t py = y + row;
            if (py < 0 || py >= bufHeight) continue;

            if (colBits & (1 << row)) {
                buffer[py * bufWidth + px] = color;
            }
        }
    }
}

int16_t drawString5x7(uint16_t* buffer, int16_t bufWidth, int16_t bufHeight, 
                      int16_t x, int16_t y, const char* str, uint16_t color, int16_t letterSpacing) {
    if (!str) return 0;
    int16_t curX = x;
    while (*str) {
        drawChar5x7(buffer, bufWidth, bufHeight, curX, y, *str, color);
        curX += (5 + letterSpacing);
        str++;
    }
    return curX - x;
}

int16_t getStringWidth5x7(const char* str, int16_t letterSpacing) {
    if (!str) return 0;
    int16_t len = 0;
    while (*str) {
        len++;
        str++;
    }
    if (len == 0) return 0;
    return (len * 5) + ((len - 1) * letterSpacing);
}
